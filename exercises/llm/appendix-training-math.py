"""LLM 底层 · 附录课 配套脚本：损失、斜率、怎么拧，三个数一次看清。

这一课只讲训练背后那点数学：损失是一个数、权重是一个数、它俩的关系由
损失函数给定；「斜率」就是对损失函数求导 —— 权重动一点、损失跟着动多少。
剩下的问题全出在把「损失值」和「斜率」这两个数混成一个。

脚本用最朴素的 L = w^2 当损失函数，把三件一直容易拌嘴的事摆到台面：
  1. 损失值 L 和斜率 dL/dw 是两个不同的数，代入 w 各算各的
  2. 扣分大不大（损失值）不直接决定「拧多少」——拧多少 = 斜率 * 学习率
  3. 反向传播传的不是「扣多少分」，而是「每个权重各自的斜率」

运行：  python exercises/llm/0000-loss-gradient-backprop.py
Windows 终端若中文乱码：先执行  chcp 65001
"""

import math

LR = 0.1  # 学习率：每一步把斜率乘上它，得到「这一步实际拧多少」


def loss(w):
    """损失公式：L = w^2。给定权重 w，算出扣多少分。"""
    return w * w


def slope(w):
    """导数公式：dL/dw = 2w（由 L = w^2 求导得到）。代入 w 得此刻斜率。"""
    return 2 * w


def step(w, lr=LR):
    """更新一「步」：新权重 = 旧权重 - 学习率 * 斜率。"""
    return w - lr * slope(w)


def tablet(w):
    """打印一个权重下的三件套：损失值、斜率、这一步实拧多少。"""
    L = loss(w)
    s = slope(w)
    moved = LR * s  # 实际拧掉的大小 = 学习率 * 斜率
    return f"  w={w:+5.1f}   损失 L=w^2={L:5.1f}   斜率 dL/dw=2w={s:+5.1f}   一步实拧 LR*s={LR}*{s:+4.1f} = {moved:+.2f}"


def main():
    print(__doc__)

    print()
    print("=" * 70)
    print("[1] 损失值和斜率是两个不同的数——代入 w 各算各的")
    print("=" * 70)
    print("  损失公式 L = w^2，导数公式 dL/dw = 2w。")
    w = 2.0
    print(f"  取 w = {w}:")
    print(f"    损失值  L(2)   = 2^2      = {loss(2):.0f}   <- 这是「扣多少分」")
    print(f"    斜率    dL/dw  = 2*2      = {slope(2):.0f}   <- 这是「w 动一点，L 动多快」")
    print("  !! 两个数都是 4，纯属巧合——换个点就分开了：")
    for w in [1.0, 3.0]:
        print(f"    w = {w}:  损失 L = {loss(w):.0f}  但  斜率 dL/dw = {slope(w):.0f}")
    print()
    print("=" * 70)
    print("[2] 扣分大不大，不直接决定拧多少——是「斜率 * 学习率」在决定")
    print("=" * 70)
    print("  挑两个不同的权重（一个扣分大、一个扣分小）比一比：")
    for w in [3.0, 1.0]:
        print(tablet(w))
    print()
    print("  w=3 那边损失 9（扣得多）、w=1 那边损失 1（扣得少）。")
    print("  「扣得多的那一侧斜率也大」，所以通常拧得多——但那是斜率的功劳，")
    print("  不是那个「9」和「1」进了算式。算式里根本没有损失值。")

    print()
    print("=" * 70)
    print("[3] 损失值干嘛用？——进度仪表盘 + 反向传播的起点")
    print("=" * 70)
    print("  每一轮（epoch）算一遍平均损失，看它在不在往下掉：")
    print("  反向传播先往前算出损失 L（前向），再沿同一条路把每个权重的斜率倒着算回去；")
    print("  「损失值」自己不乘进更新，但没有那一趟前向，斜率连起点都没有。")
    print("  （真实模型是几十层套娃，靠链式法则从后往前传——这里只演示单权重版。）")

    print()
    print("=" * 70)
    print("[4] 走几步看看：损失往下掉，就是「往少扣分方向拧」在生效")
    print("=" * 70)
    w = 5.0  # 从离谷底（w=0，损失 0）很远的地方出发
    print("  从 w = 5 出发，学习率 0.1，每步新权重 = 旧权重 - 0.1*2w：")
    for i in range(6):
        print(f"    第 {i} 步  w={w:+6.3f}   损失 L={loss(w):6.3f}")
        w = step(w)
    print("  w 一路被推向 0（谷底），损失一路缩到接近 0——方向来自斜率 dL/dw=2w 的符号：")
    print("  w>0 时斜率>0（该减小 w），w<0 时斜率<0（该增大 w），都朝 w=0 收敛。")

    print()
    print("=" * 70)
    print("[5] 一句话")
    print("=" * 70)
    print("  损失是「现在站在坡上多高」（w→L）；斜率是「往哪边、多快往下」（dL/dw）；")
    print("  拧多少 = 斜率 * 学习率——损失值的数字不乘进去，但算出它（前向）是拿到斜率的必经路。")
    print("  反向传播 = 把「每个权重各自的斜率」从损失公式里一个个算出来的那套算法。")


if __name__ == "__main__":
    main()
