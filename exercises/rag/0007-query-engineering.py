"""RAG · 第 7 课 · 配套脚本：一句原话，怎么变成检索器能用的查询。

对应第 7 课的五个动作：改写、拆开、升高、HyDE、查之前分流。
同一个员工手册库，同一套检索规则，只换【查询】——看哪一句能捞到答案。

你会看到：
  1. 「那还能休几天？」——没有主语，检索器捞不到
  2. 改写补上「病假」——同一句话，捞到了
  3. 改写过头——把关键词改没，检索直接归零
  4. 一句话里三个问题——拆成三问，覆盖率从 2/3 到 3/3
  5. 「晚归能不能晚点到」——升一层问规则，才捞得到
  6. 「假期用不掉会作废吗」——先编一个假答案，再去查
  7. 查之前先分流：该不该查、查哪个库、查不到怎么办

⚠ 这里的检索器是玩具：只数【两字组合】撞上多少，不调模型。
  真的嵌入模型还会做语义匹配——但「查询里根本没说的词，它补不出来」
  这件事一模一样。第 6 课已经看过稀疏和稠密各会怎么翻车。

运行：  python exercises/rag/0007-query-engineering.py
Windows 终端若中文乱码：先执行  chcp 65001
"""

# ============ 资料库：员工手册 ============
DOCS = {
    1: ("hr", "年假天数", "员工入职满一年不满十年，每年年假 5 天；满十年不满二十年，每年 10 天；满二十年及以上，每年 15 天。"),
    2: ("hr", "年假折算", "年度中间入职的员工，当年年假按剩余日历天数折算，折算后不足 1 天的部分不计。"),
    3: ("hr", "病假", "员工每年享有 5 天带薪病假，超过 5 天的部分按事假处理。"),
    4: ("hr", "陪产假", "男员工配偶生育，可休 15 天陪产假，需在生育后三个月内休完。"),
    5: ("hr", "请假流程", "请假三天以内（含三天）向直属主管口头报备；三天以上在系统提交申请单。"),
    6: ("hr", "年假结转", "当年未休完的年假，可以结转至次年第一季度，逾期未休的部分清零。"),
    7: ("hr", "弹性工作", "因公出差或加班至晚上十点以后，次日可申请十点前到岗。"),
    8: ("fin", "差旅报销", "差旅住宿费：一线城市每晚不超过 600 元，其他城市每晚不超过 450 元。"),
    9: ("fin", "餐补", "工作日午餐补贴每人每天 20 元，随当月工资发放。"),
}


def pairs(text):
    return [text[i:i + 2] for i in range(len(text) - 1)]


def score(query, doc):
    """玩具检索：数查询和文档共有多少个两字组合。真实系统比这聪明得多。"""
    q = set(pairs(query))
    return sum(1 for p in pairs(doc) if p in q)


def top(query, k=3):
    """返回 [(分数, 编号)]，只留真有分的段——0 分不是「最不相关」，是「没撞上」。"""
    ranked = sorted(((score(query, t), i) for i, (_, _, t) in DOCS.items()),
                    key=lambda x: (-x[0], x[1]))
    return [x for x in ranked if x[0] > 0][:k]


def show(label, query, k=3):
    hits = top(query, k)
    if not hits:
        print(f"      {label}：0 段命中（查询里没有一个词撞上资料库）")
        return []
    body = "　".join(f"段{i}（{DOCS[i][1]}，{s} 分）" for s, i in hits)
    print(f"      {label}：{body}")
    return [i for _, i in hits]


def coverage(hit_ids, gold):
    got = sorted(set(hit_ids) & set(gold))
    return f"{len(got)}/{len(gold)}（{'、'.join('段'+str(i) for i in got) or '无'}）"


# ============ 1. 改写：补上省略的主语 ============
print("[1] 改写：原话省略了什么，查询就缺什么")
print("      多轮对话里，用户刚问完病假，接着问：")
show("原话", "那还能休几天？")
print("      → 0 段。检索器不知道「那」指的是病假，也不知道该拿「病假」去撞。")
print("      把上文的指代补回查询里：")
show("改写后", "病假有几天？")
print("      → 段 3（病假）。同一句话，补上主语就捞到了。")
print("      ⚠ 只改【检索用的那一份】，用户看到的回答不必重复改写后的句子。")

# ============ 2. 改写过头 ============
print("\n[2] 改写过头：把关键词改没了")
q0 = "年假没休完能留到明年吗？"
print(f"      原话：「{q0}」")
show("原话去查", q0)
print("      改成更「书面」的说法：「公司休假制度有哪些规定？」")
show("过度改写", "公司休假制度有哪些规定？")
print("      → 0 段。听起来更正式，可「年假」「休完」「明年」这些能撞上的词全没了。")
print("      改写的边界：补信息、换同义词可以；【别把编号、术语、时间这些锚点改掉】。")

# ============ 3. 拆开：一句话里三个问题 ============
print("\n[3] 拆开：一句话里藏着三个可检索的问题")
q = "我 2021 年 3 月入职，今年年假能休几天，没休完能留到明年吗？"
gold = [1, 2, 6]  # 天数、折算、结转
print(f"      原话：「{q}」")
single = show("整句去查（取前 2 段）", q, k=2)
print(f"      覆盖答案段：{coverage(single, gold)}")
print("      → 整句只捞到「天数」和「折算」，没捞到「结转」——")
print("        因为一句话里塞了三件事，前两段被更显眼的词占满了。")
subqs = [
    "2021 年 3 月入职，当年的年假怎么折算？",
    "年假每年有多少天？",
    "年假没休完能不能结转？",
]
print("      拆成三个子问题，各查各的：")
all_hits = []
for sq in subqs:
    hits = show("· " + sq, sq, k=1)
    all_hits += hits
print(f"      合起来覆盖：{coverage(all_hits, gold)}")
print("      → 三段全到齐。代价是三次检索，外加一次把答案拼起来的调用。")

# ============ 4. 升高：先问规则，再套个案 ============
print("\n[4] 升高一层：个案查不到，就查它背后的规则")
q_direct = "昨晚陪客户到半夜，今天早上能晚点去吗？"
show("按原话查", q_direct)
print("      → 0 段。文档里没有「陪客户」「半夜」「晚点去」这些说法。")
q_back = "因公晚归后，次日上班时间怎么规定？"
show("升一层查", q_back)
print("      → 段 7（弹性工作）。先拿到「因公晚归→次日可申请十点前到岗」这条规则，")
print("        再拿它去判断「陪客户算不算因公」——这一步交给生成那一步。")

# ============ 5. HyDE：先编一个假答案 ============
print("\n[5] HyDE：问题太短，先编一个「像文档的答案」再去查")
q_h = "假期用不掉会作废吗？"
show("按原话查", q_h)
print("      → 0 段。「用不掉」跟「未休完」、「作废」跟「清零」都没撞上。")
fake = "未休完的年假可以结转至次年第一季度，逾期未休的部分清零，也可以申请折现。"
print(f"      假答案：「{fake}」")
show("拿假答案去查", fake)
print("      → 段 6（年假结转）。假答案里那句「可以折现」是编的，")
print("        但检索器只拿它当【一串用来找路的词】；真正的答案仍以捞回的原文为准。")
print("      ⚠ 编号、金额、日期这类必须逐字对上的问题，别用 HyDE——假答案会把它们编歪。")

# ============ 6. 查之前先分流 ============
print("\n[6] 查之前先分流：该不该查、查哪个库、查不到怎么办")
ROUTES = [
    (("年假", "病假", "陪产假", "请假", "休假"), "hr", "查 HR 手册"),
    (("报销", "差旅", "住宿", "餐补", "发票"), "fin", "查财务制度"),
]
NO_RETRIEVAL = ("天气", "新闻", "股票", "写一封", "翻译", "讲个笑话")

cases = ["陪产假有几天？", "住宿费一晚能报多少？", "今天天气怎么样？", "帮我写一封辞职信。"]
for c in cases:
    if any(w in c for w in NO_RETRIEVAL):
        print(f"      「{c}」→ 不查资料库：这不是资料库里能答的问题，走别的路")
        continue
    route = next((r for words, r, _ in ROUTES if any(w in c for w in words)), None)
    if route:
        print(f"      「{c}」→ 路由到 {route} 库：只在这个库里检索")
    else:
        print(f"      「{c}」→ 没有匹配的库：先反问或明说范围，别硬查")

print("\n      还有一个必须承认的结果：查不到。")
show("「公司有班车吗？」", "公司有班车吗？")
print("      → 0 段。这时候正确的话是「资料里没有」，不是拿别的段硬凑。")
print("        生成侧怎么把这句话说好，是第 8 课的事。")

# ============ 7. 带走 ============
print("\n[7] 带走五条")
print("      ① 用户说的是给人听的话，查询是给检索器看的话——两者中间要加工。")
print("      ② 改写补全（指代、口语），但别改掉编号、术语、时间这些锚点。")
print("      ③ 一句多问就拆开；拆完逐个查，再合并。代价是检索次数翻倍。")
print("      ④ 个案查不到，升一层查规则；短查询撞不上文档，就用假答案换一种说法。")
print("      ⑤ 查之前先分流：不该查的别查，查不到的别编。")
