"""RAG · 第 4 课 配套脚本：两种典型翻车，长得完全不一样。

RAG 答错了，原因只有两类：
  ① 该来的没来 —— 检索压根没找到那段（问题在前五步）
  ② 来了但没用上 —— 检索到了、也塞了，模型没用它（问题在最后一步）
两类要分开诊断，因为解法完全相反。

脚本不调任何模型，只做一件事：【把模型会看到的那一屏打出来】。
答案在不在里面，你一眼就能看出来——这就是全部的诊断方法。

运行：  python exercises/rag/0004-two-failure-modes.py
Windows 终端若中文乱码：先执行  chcp 65001
"""

# ============ 一份资料库（同第 1 课） ============
DOCS = [
    "年假天数：入职满一年者每年 5 天，满三年者 10 天，满五年者 15 天。",
    "请假三天以内（含三天），向直属主管口头报备即可，事后补一条消息。",
    "请假三天以上，需在系统里提交申请单，附上证明材料，主管审批后生效。",
    "报销流程：每月 25 日前提交发票，财务在次月 15 日统一打款。",
    "加班调休：加班满 4 小时可调休半天，调休需当月用完，过期作废。",
]


def show_prompt(chunks, q, tag=""):
    print("      ┌──────────────────────────────────────")
    for i, c in enumerate(chunks, 1):
        mark = " ◀◀ 答案在这儿" if tag and tag in c else ""
        print(f"      │【资料 {i}】{c}{mark}")
    print(f"      │【问题】{q}")
    print("      └──────────────────────────────────────")


# ============ 场景 A：该来的没来 ============
print("[1] 场景 A · 该来的没来（检索没找到）")
print("      问题：「我入职四年，年假有几天？」")
print("      资料库里明明有答案：")
print(f"        {DOCS[0]}")
print()
print("      但检索只取了 1 段（top-k = 1），而且问法跟原文的说法对不上，")
print("      结果拿到的是这一段：")
show_prompt([DOCS[1]], "我入职四年，年假有几天？")
print("      → 模型看到的那一屏里，【根本没有答案】。它只能编。")
print("      这就是第一类：该来的没来。")

# ============ 诊断方法 ============
print("\n[2] 全部诊断方法就一句：把模型会看到的那一屏打出来，人眼看")
print("      答案在里面吗？")
print("        不在 → 第一类，去修前五步（切块 / 变向量 / 取几段）")
print("        在   → 第二类，去看下面场景 B")

# ============ 场景 B：来了但没用上 ============
print("\n[3] 场景 B · 来了但没用上（检索到了，模型没用）")
print("      问题：「请三天假要走什么流程？」")
print("      这次检索给了 8 段，正确的那两段【都在里面】——但排在中间。")
padded = [
    "办公用品领用：每人每月限领签字笔 2 支、笔记本 1 本。",
    "会议室预约：提前 1 天在系统预约，超时 15 分钟自动释放。",
    "门禁卡办理：入职当天由行政统一办理，遗失补办 20 元。",
    DOCS[1],   # 答案 ① 在第 4 位（8 段里的正中间）
    DOCS[2],   # 答案 ② 在第 5 位
    "打印机使用：公共打印机在三楼东侧，故障报修走 IT 工单。",
    "快递收发：公司统一收发，个人快递请勿寄到前台。",
    "工位调整：每季度可申请一次，由部门助理统一报备。",
]
show_prompt(padded, "请三天假要走什么流程？", tag="请假三天")
print("      → 答案在，可它被埋在【正中间】。")
print("      实测结论（Liu et al. 2023）：相关信息排在长上下文中间时，")
print("      模型的成绩会掉到【比完全不给资料还差】。放开头或结尾才好使。")
print("      这就是第二类：来了但没用上。")

