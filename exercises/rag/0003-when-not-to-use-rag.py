"""RAG · 第 3 课 配套脚本：什么时候【不该】上 RAG。

RAG 只解决一个问题：【模型手上没有那份资料】。
别的问题——要精确值、要实时数据、要推理——它解决不了，甚至更糟。

脚本不调任何模型，就是一个判断练习：
  先把 6 个场景全打出来，你自己想一遍该不该上 RAG；
  再往下滚，看答案和理由。

运行：  python exercises/rag/0003-when-not-to-use-rag.py
Windows 终端若中文乱码：先执行  chcp 65001
"""

SCENES = [
    (
        "公司内部的报销与休假制度，全文约 8000 字，员工随时会问其中某一条。",
        "该上",
        "模型没见过你的内部文件，而答案确实在里面——这正是 RAG 唯一要解决的问题。",
    ),
    (
        "一份 500 字的产品说明书，用户会围绕它提问。",
        "不该上，直接塞",
        "500 字整个塞进提示词就行。切块只会额外引入「切碎 / 检索不到」两种新毛病。",
    ),
    (
        "用户问：我账户里现在还有多少钱？",
        "不该上，用工具查",
        "余额每分钟都在变。向量库里存的是【建库那天】的快照，查出来必错。",
    ),
    (
        "用户问：今天北京多少度？",
        "不该上，用工具查",
        "实时数据。同上——检索给不了「现在」。",
    ),
    (
        "老板要你把三份合同的付款条款差异列成一张表。",
        "不该上，或只当资料入口",
        "要的是跨段推理与对比，检索只能给你「相关的几段」。硬上还可能漏掉某一份的条款。",
    ),
    (
        "查错误码 E-2107 是什么意思。文档里有 3000 个错误码。",
        "该上，但要用「按词匹配」",
        "错误码是精确编号，语义相似度反而抓不准（它连 2107 和 2108 都分不太清）。用稀疏检索。",
    ),
]


def main():
    print("=" * 70)
    print("先别往下看。6 个场景，你先各判一下：该不该上 RAG？")
    print("=" * 70)
    for i, (scene, _, _) in enumerate(SCENES, 1):
        print(f"\n  场景 {i}：{scene}")

    print("\n" + "=" * 70)
    print("想好了？下面是判断和理由")
    print("=" * 70)
    for i, (scene, verdict, why) in enumerate(SCENES, 1):
        print(f"\n  场景 {i}：{scene}")
        print(f"    → {verdict}")
        print(f"    理由：{why}")

    print("\n" + "=" * 70)
    print("带走一句口诀")
    print("=" * 70)
    print("  第一问：模型手上有没有这份资料？")
    print("        没有 → 往下问；有 → 别上 RAG。")
    print("  第二问：我要的是【查得到的事实】，还是【要推理】？")
    print("        事实且会变 / 很精确 → 用工具查，别用检索。")
    print("        事实且稳定、量大 → 这才是 RAG 的地盘。")
    print("        要推理 → RAG 只能当资料入口，别指望它给结论。")


if __name__ == "__main__":
    main()
