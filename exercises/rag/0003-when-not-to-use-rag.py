"""RAG · 第 3 课 配套脚本：该不该上 RAG，三条路怎么选。

三条路：
  RAG（建库检索）      补「资料不在模型手边」
  长上下文（直接塞）    省掉建库这一步，把整份资料拼进提示词
  微调（改行为）        改「怎么答」：口径、格式、语气、红线
另有两个不属于上面三条的出口：
  工具查                要「此刻的值」或「会变的数」
  先不用                资料在模型手边，或者问题本身不靠资料

「模型不够强」不在这份判断里：那是换模型或拆活，不是资料怎么递。

脚本不调任何模型，就是一个判断练习：
  先把 8 个场景全打出来，你自己判一遍；
  再往下滚，看路线、理由和判断顺序。

运行：  python exercises/rag/0003-when-not-to-use-rag.py
Windows 终端若中文乱码：先执行  chcp 65001
"""

SCENES = [
    (
        "公司内部的制度汇编，几百份文件，每月改版，员工每天会问其中不同的一条，答完还要能追到具体条款。",
        "RAG（建库检索）",
        "问的人多、制度常改、要出处，这正是 RAG 的地盘。制度改版时换文档重嵌，不用重新训练模型。",
    ),
    (
        "一份 500 字的产品说明书，用户会围绕它提问。",
        "长上下文（直接塞）",
        "500 字整个塞进提示词就行。建库会额外引入「切碎 / 检索不到」两种新毛病，为省事反而买麻烦。",
    ),
    (
        "用户问：我账户里现在还有多少钱？",
        "工具查（不是检索）",
        "余额每分钟都在变。向量库里存的是建库那天的快照，查出来必错。",
    ),
    (
        "用户问：今天北京多少度？",
        "工具查（不是检索）",
        "实时数据。同上——检索给不了「现在」。",
    ),
    (
        "老板要你把三份合同的付款条款差异列成一张表，每份约 30 页。",
        "长上下文（直接塞）",
        "三份都塞得下，而且对比要同时看到全文。检索只给「相关的几段」，可能漏掉某一份的附加条款。",
    ),
    (
        "查错误码 E-2107 是什么意思。文档里有 3000 个错误码。",
        "RAG，但要用「按词匹配」",
        "错误码是精确编号，语义相似度反而抓不准（它连 2107 和 2108 都分不太清）。该上 RAG，但要开稀疏检索。",
    ),
    (
        "客服回复必须先带免责声明、语气统一、任何情况下不承诺赔偿。",
        "微调（改行为）",
        "这是「怎么答」的规矩，微调正对路。具体条款和金额仍由 RAG 提供——微调搬不动事实条目。",
    ),
    (
        "制度每月改版，员工问答要带出处，答错了要能追到是哪一条。",
        "RAG（建库检索）",
        "要出处、要跟着改版走，检索比微调合适：换文档就生效，引用还能落回原文。",
    ),
]


def main():
    print("=" * 72)
    print("先别往下看。8 个场景，你先各判一下：该走哪条路？")
    print("=" * 72)
    for i, (scene, _, _) in enumerate(SCENES, 1):
        print(f"\n  场景 {i}：{scene}")

    print("\n" + "=" * 72)
    print("想好了？下面是判断和理由")
    print("=" * 72)
    for i, (scene, route, why) in enumerate(SCENES, 1):
        print(f"\n  场景 {i}：{scene}")
        print(f"    → {route}")
        print(f"    理由：{why}")

    print("\n" + "=" * 72)
    print("带走一张判断顺序")
    print("=" * 72)
    print("  第一问：要的是「此刻的值」或「会变的数」吗？")
    print("          是 → 用工具查（API、数据库、搜索），不是检索。")
    print("          否 → 往下。")
    print("  第二问：毛病在「答什么」，还是「怎么答」？")
    print("          「怎么答」：口径、格式、语气、红线 → 微调（事实仍走下面）。")
    print("          「答什么」：制度、条款、数字、案例 → 往下。")
    print("  第三问：资料塞得下吗？")
    print("          塞不下 → RAG。")
    print("          塞得下 → 往下。")
    print("  第四问：值得为它建库吗？")
    print("          几十页以内 → 长上下文。")
    print("          上百页：很多人问，或者资料多到需要逐条追来源 → RAG。")
    print("                  只是少数人偶尔问 → 长上下文。")


if __name__ == "__main__":
    main()
